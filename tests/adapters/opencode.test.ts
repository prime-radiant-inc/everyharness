describe('opencode adapter with bootstrap: none', () => {
  it('omits the bootstrap cache and message-transform hook, keeping only the config hook', () => {
    const dir = tmpFixture('name: none-demo\nversion: 1.0.0\ndescription: bootstrap-none fixture\nbootstrap:\n  none: true\n')
    const noneModel = buildModel(dir)
    const js = opencode.emit(noneModel).files.find((f) => f.path === '.opencode/plugins/none-demo.js')!.content
    expect(js).not.toContain('_bootstrapCache')
    expect(js).not.toContain('experimental.chat.messages.transform')
    expect(js).not.toContain('BOOTSTRAP_MARKER')
    expect(js).toContain('config.skills.paths.push(skillsDir)')
    expect(js).not.toMatch(/__[A-Z_]+__/)
  })
})

describe('opencode plugin JS — dynamic import execution (skill mode)', () => {
  it('registers the skills dir idempotently and injects the bootstrap exactly once across repeated transform calls', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'eh-opencode-exec-'))
    writeFileSync(
      join(dir, 'everyharness.yaml'),
      'name: demo\nversion: 1.0.0\ndescription: exec fixture\nbootstrap:\n  skill: using-demo\n',
    )
    mkdirSync(join(dir, 'skills', 'using-demo'), { recursive: true })
    writeFileSync(
      join(dir, 'skills', 'using-demo', 'SKILL.md'),
      '---\nname: using-demo\ndescription: exec fixture skill\n---\n\n# Using Demo\n\nDemo skill body.\n',
    )

    const demoModel = buildModel(dir)
    const result = opencode.emit(demoModel)
    writeFileSet(dir, result.files)

    const pluginAbsPath = join(dir, '.opencode', 'plugins', 'demo.js')
    const mod = (await import(pathToFileURL(pluginAbsPath).href)) as Record<string, unknown>
    const factory = mod.DemoPlugin as (opts: { client: null; directory: string }) => Promise<{
      config: (config: { skills?: { paths?: string[] } }) => Promise<void>
      'experimental.chat.messages.transform': (
        input: unknown,
        output: { messages: Array<{ info: { role: string }; parts: Array<{ type: string; text: string }> }> },
      ) => Promise<void>
    }>
    expect(typeof factory).toBe('function')

    const instance = await factory({ client: null, directory: '' })

    // config hook: idempotent across repeated calls.
    const config: { skills: { paths: string[] } } = { skills: { paths: [] } }
    await instance.config(config)
    await instance.config(config)
    expect(config.skills.paths).toEqual([join(dir, 'skills')])

    // transform hook: exactly one bootstrap part after two calls.
    const output = {
      messages: [{ info: { role: 'user' }, parts: [{ type: 'text', text: 'hi' }] }],
    }
    await instance['experimental.chat.messages.transform']({}, output)
    await instance['experimental.chat.messages.transform']({}, output)

    const bootstrapParts = output.messages[0].parts.filter(
      (p) => p.type === 'text' && p.text.includes('<plugin-bootstrap plugin="demo">'),
    )
    expect(bootstrapParts).toHaveLength(1)
    expect(output.messages[0].parts).toHaveLength(2)
    expect(bootstrapParts[0].text).toContain('Demo skill body.')
    expect(bootstrapParts[0].text).not.toContain('name: using-demo')
  })
})

describe('opencode plugin JS — dynamic import execution (bootstrap: none)', () => {
  it('exposes only the config hook', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'eh-opencode-exec-none-'))
    writeFileSync(
      join(dir, 'everyharness.yaml'),
      'name: nodemo\nversion: 1.0.0\ndescription: exec none fixture\nbootstrap:\n  none: true\n',
    )
    mkdirSync(join(dir, 'skills', 'demo'), { recursive: true })
    writeFileSync(join(dir, 'skills', 'demo', 'SKILL.md'), '---\nname: demo\ndescription: demo\n---\n\nBody.\n')

    const noneModel = buildModel(dir)
    const result = opencode.emit(noneModel)
    writeFileSet(dir, result.files)

    const pluginAbsPath = join(dir, '.opencode', 'plugins', 'nodemo.js')
    const mod = (await import(pathToFileURL(pluginAbsPath).href)) as Record<string, unknown>
    const factory = mod.NodemoPlugin as (opts: { client: null; directory: string }) => Promise<Record<string, unknown>>
    const instance = await factory({ client: null, directory: '' })

    expect(instance['experimental.chat.messages.transform']).toBeUndefined()

    const config: { skills: { paths: string[] } } = { skills: { paths: [] } }
    await (instance.config as (c: typeof config) => Promise<void>)(config)
    expect(config.skills.paths).toEqual([join(dir, 'skills')])
  })
})
