import { describe, it, expect } from 'vitest'
import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { buildModel } from '../../src/model.js'
import { claudeCode } from '../../src/adapters/claude-code.js'
import { adapters, getAdapter } from '../../src/adapters/index.js'

const model = buildModel('fixtures/kitchen-sink')

describe('adapter registry', () => {
  it('registers claude-code', () => {
    expect(adapters.map((a) => a.name)).toContain('claude-code')
    expect(getAdapter('claude-code')).toBe(claudeCode)
    expect(getAdapter('nope')).toBeUndefined()
  })
})

describe('claude-code adapter', () => {
  const result = claudeCode.emit(model)
  const byPath = Object.fromEntries(result.files.map((f) => [f.path, f.content]))

  it('emits plugin.json with config fields, override merge, and mcp path', () => {
    const manifest = JSON.parse(byPath['.claude-plugin/plugin.json'])
    expect(manifest).toEqual({
      name: 'kitchen-sink',
      version: '0.1.0',
      description: 'Fixture plugin exercising every component type',
      author: { name: 'Prime Radiant', email: 'dev@prime-radiant.example' },
      license: 'MIT',
      repository: 'https://github.com/prime-radiant-inc/everyharness',
      keywords: ['fixture'],
      homepage: 'https://example.com/kitchen-sink',
      hooks: './hooks/everyharness/hooks.json',
    })
  })

  it('emits a dev marketplace listing the plugin at source ./', () => {
    const marketplace = JSON.parse(byPath['.claude-plugin/marketplace.json'])
    expect(marketplace.name).toBe('kitchen-sink-dev')
    expect(marketplace.owner).toEqual({ name: 'Prime Radiant', email: 'dev@prime-radiant.example' })
    expect(marketplace.plugins).toEqual([
      {
        name: 'kitchen-sink',
        description: 'Fixture plugin exercising every component type',
        version: '0.1.0',
        source: './',
        author: { name: 'Prime Radiant', email: 'dev@prime-radiant.example' },
        category: 'Developer Tools',
        keywords: ['demo', 'fixture']
      }
    ])
  })

  it('emits no warnings for full-support components', () => {
    expect(result.warnings).toEqual([])
  })

  it('declares full support for every component', () => {
    expect(Object.values(claudeCode.support).every((level) => level === 'full')).toBe(true)
  })

  it('emits an executable bootstrap session-start hook', () => {
    const file = result.files.find((f) => f.path === 'hooks/everyharness/session-start')
    expect(file?.executable).toBe(true)
    expect(file?.content).toContain('skills/using-kitchen-sink/SKILL.md')
  })

  it('emits an executable run-hook.cmd polyglot', () => {
    const file = result.files.find((f) => f.path === 'hooks/everyharness/run-hook.cmd')
    expect(file?.executable).toBe(true)
    expect(file?.content.startsWith(": << 'CMDBLOCK'")).toBe(true)
  })

  it('emits hooks.json merging the fixture hook with the bootstrap SessionStart entry', () => {
    const hooks = JSON.parse(byPath['hooks/everyharness/hooks.json'])
    expect(hooks.hooks.SessionStart).toHaveLength(2)
    expect(JSON.stringify(hooks.hooks.SessionStart[1])).toContain('hooks/everyharness/run-hook.cmd')
  })
})

describe('claude-code adapter with bootstrap.generate', () => {
  it('emits no warnings and a generated bootstrap.md wired into the session-start hook', () => {
    const dir = mkdtempSync(join(tmpdir(), 'eh-claude-code-generate-'))
    mkdirSync(join(dir, 'skills', 'demo'), { recursive: true })
    writeFileSync(
      join(dir, 'skills', 'demo', 'SKILL.md'),
      '---\nname: demo\ndescription: demo skill for generate-mode fixture\n---\n\nBody.\n',
    )
    writeFileSync(
      join(dir, 'everyharness.yaml'),
      'name: generate-bootstrap\nversion: 1.0.0\ndescription: bootstrap.generate fixture\nbootstrap:\n  generate: true\n',
    )
    const generateModel = buildModel(dir)
    const result = claudeCode.emit(generateModel)
    expect(result.warnings).toEqual([])
    const bootstrapMd = result.files.find((f) => f.path === 'hooks/everyharness/bootstrap.md')
    expect(bootstrapMd?.content).toBe(
      [
        '<!-- GENERATED by everyharness — edit everyharness.yaml instead -->',
        '# generate-bootstrap plugin',
        '',
        'Invoke the relevant skill BEFORE acting when a task matches its description.',
        '',
        '- **demo**: demo skill for generate-mode fixture',
        '',
      ].join('\n'),
    )
    const sessionStart = result.files.find((f) => f.path === 'hooks/everyharness/session-start')
    expect(sessionStart?.executable).toBe(true)
    expect(sessionStart?.content).toContain('hooks/everyharness/bootstrap.md')
    const manifest = JSON.parse(result.files.find((f) => f.path === '.claude-plugin/plugin.json')!.content)
    expect(manifest.hooks).toBe('./hooks/everyharness/hooks.json')
  })
})

describe('claude-code adapter installDoc', () => {
  it('produces an exact body for the kitchen-sink fixture: emitted files, marketplace mechanism, hooks-merge caveat', () => {
    expect(claudeCode.installDoc!(model)).toBe(
      [
        '## What gets emitted',
        '',
        '- `.claude-plugin/plugin.json` and `.claude-plugin/marketplace.json`',
        '- the `hooks/everyharness` bootstrap hook and its merged `hooks/everyharness/hooks.json`',
        '',
        '## Installing',
        '',
        'Register the marketplace, then install the plugin:',
        '',
        '```',
        'claude /plugin marketplace add prime-radiant-inc/everyharness',
        '```',
        '',
        '```',
        '/plugin install kitchen-sink@kitchen-sink-dev',
        '```',
        '',
        "If the marketplace is already registered, only the install command is needed. Consult Claude Code's plugin docs if these commands don't match your installed version.",
        '',
        '## Caveats',
        '',
        '- Hand-written entries in `hooks/hooks.json` are merged into the generated `hooks/everyharness/hooks.json`; edit the source file, not the generated file.',
      ].join('\n'),
    )
  })

  it('falls back to <your-repo> when config.repository is absent', () => {
    const dir = mkdtempSync(join(tmpdir(), 'eh-claude-code-installdoc-norepo-'))
    writeFileSync(
      join(dir, 'everyharness.yaml'),
      'name: no-repo\nversion: 1.0.0\ndescription: no repository fixture\nbootstrap:\n  none: true\n',
    )
    const noRepoModel = buildModel(dir)
    const body = claudeCode.installDoc!(noRepoModel)
    expect(body).toContain('claude /plugin marketplace add <your-repo>')
    expect(body).toContain('/plugin install no-repo@no-repo-dev')
  })

  it('falls back to <your-repo> when config.repository is not a github.com URL', () => {
    const dir = mkdtempSync(join(tmpdir(), 'eh-claude-code-installdoc-nongithub-'))
    writeFileSync(
      join(dir, 'everyharness.yaml'),
      'name: non-github\nversion: 1.0.0\ndescription: non-github repository fixture\nrepository: https://gitlab.com/owner/repo\nbootstrap:\n  none: true\n',
    )
    const nonGithubModel = buildModel(dir)
    expect(claudeCode.installDoc!(nonGithubModel)).toContain('claude /plugin marketplace add <your-repo>')
  })

  it('omits the bootstrap hook line and the Caveats section when bootstrap is not active', () => {
    const dir = mkdtempSync(join(tmpdir(), 'eh-claude-code-installdoc-nobootstrap-'))
    writeFileSync(
      join(dir, 'everyharness.yaml'),
      'name: no-bootstrap\nversion: 1.0.0\ndescription: no bootstrap fixture\nbootstrap:\n  none: true\n',
    )
    const noBootstrapModel = buildModel(dir)
    const body = claudeCode.installDoc!(noBootstrapModel)
    expect(body).not.toContain('bootstrap hook')
    expect(body).not.toContain('## Caveats')
  })
})

describe('claude-code adapter with a non-default skills path', () => {
  it('emits a skills key in plugin.json pointing at the custom directory', () => {
    const dir = mkdtempSync(join(tmpdir(), 'eh-claude-code-'))
    writeFileSync(
      join(dir, 'everyharness.yaml'),
      'name: custom-skills\nversion: 1.0.0\ndescription: custom skills path fixture\ncomponents:\n  skills: my-skills\n',
    )
    mkdirSync(join(dir, 'my-skills', 'demo'), { recursive: true })
    writeFileSync(
      join(dir, 'my-skills', 'demo', 'SKILL.md'),
      '---\nname: demo\ndescription: demo skill for custom path test\n---\n\nBody.\n',
    )
    const customModel = buildModel(dir)
    const result = claudeCode.emit(customModel)
    const manifest = JSON.parse(result.files.find((f) => f.path === '.claude-plugin/plugin.json')!.content)
    expect(manifest.skills).toBe('./my-skills')
  })
})
