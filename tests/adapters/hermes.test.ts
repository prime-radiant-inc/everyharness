describe('hermes adapter with bootstrap.generate', () => {
  it('resolves the bootstrap path to the generated bootstrap.md', () => {
    const dir = tmpFixture('name: gen-demo\nversion: 1.0.0\ndescription: generate-mode fixture\nbootstrap:\n  generate: true\n')
    const genModel = buildModel(dir)
    const files = hermes.emit(genModel).files
    const py = files.find((f) => f.path === '.hermes-plugin/__init__.py')!.content
    const bootstrapParts = GENERATED_BOOTSTRAP_PATH.split('/')
      .map((p) => `"${p}"`)
      .join(', ')
    expect(py).toContain(`"${GENERATED_BOOTSTRAP_PATH}".split("/")`)
    expect(py).not.toMatch(/__[A-Z_]+__/)
    expect(pyCompile(py).status).toBe(0)
    // sanity: GENERATED_BOOTSTRAP_PATH really does have the shape we assume
    expect(bootstrapParts).toBeTruthy()

    const yamlContent = files.find((f) => f.path === '.hermes-plugin/plugin.yaml')!.content
    const rest = yamlContent.split('\n').slice(1).join('\n')
    expect(parse(rest)).toEqual({
      name: 'gen-demo',
      version: '1.0.0',
      description: 'generate-mode fixture',
      provides_hooks: ['pre_llm_call'],
    })
  })

  it('emits the generated bootstrap.md file itself, not just a reference to it', () => {
    const dir = tmpFixture('name: gen-demo\nversion: 1.0.0\ndescription: generate-mode fixture\nbootstrap:\n  generate: true\n')
    const genModel = buildModel(dir)
    const bootstrapMd = hermes.emit(genModel).files.find((f) => f.path === GENERATED_BOOTSTRAP_PATH)
    expect(bootstrapMd?.content).toContain('# gen-demo plugin')
  })
})

describe('hermes adapter with bootstrap: none', () => {
  const dir = tmpFixture('name: none-demo\nversion: 1.0.0\ndescription: bootstrap-none fixture\nbootstrap:\n  none: true\n')
  const noneModel = buildModel(dir)
  const files = hermes.emit(noneModel).files
  const py = files.find((f) => f.path === '.hermes-plugin/__init__.py')!.content
  const yamlContent = files.find((f) => f.path === '.hermes-plugin/plugin.yaml')!.content

  it('omits pre_llm_call, BOOTSTRAP_MARKER, and register_hook entirely', () => {
    expect(py).not.toMatch(/__[A-Z_]+__/)
    expect(py).not.toContain('pre_llm_call')
    expect(py).not.toContain('BOOTSTRAP_MARKER')
    expect(py).not.toContain('register_hook')
    expect(py).toContain('def register(ctx):')
    expect(py).toContain('Path(skill_md)')
  })

  it('compiles cleanly with python3 -m py_compile', () => {
    expect(pyCompile(py).status).toBe(0)
  })

  it('omits provides_hooks from plugin.yaml', () => {
    const rest = yamlContent.split('\n').slice(1).join('\n')
    const parsed = parse(rest) as Record<string, unknown>
    expect(parsed).not.toHaveProperty('provides_hooks')
    expect(parsed).toEqual({
      name: 'none-demo',
      version: '1.0.0',
      description: 'bootstrap-none fixture',
    })
  })
})

