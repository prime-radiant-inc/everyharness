describe('hermes plugin.py -- execution smoke test', () => {
  it('registers skills as Path instances and injects the bootstrap marker via the captured pre_llm_call hook', () => {
    const dir = mkdtempSync(join(tmpdir(), 'eh-hermes-exec-'))
    writeFileSync(
      join(dir, 'everyharness.yaml'),
      'name: demo\nversion: 1.0.0\ndescription: exec fixture\nbootstrap:\n  skill: using-demo\n',
    )
    mkdirSync(join(dir, 'skills', 'using-demo'), { recursive: true })
    writeFileSync(
      join(dir, 'skills', 'using-demo', 'SKILL.md'),
      '---\nname: using-demo\ndescription: exec fixture skill\n---\n\n# Using Demo\n\nDemo skill body.\n',
    )

    const demoModel = buildModel(dir)
    const result = hermes.emit(demoModel)
    writeFileSet(dir, result.files)

    const initPath = join(dir, '.hermes-plugin', '__init__.py')
    const driverPath = join(dir, 'driver.py')
    writeFileSync(
      driverPath,
      [
        'import importlib.util',
        'import pathlib',
        'import sys',
        '',
        `spec = importlib.util.spec_from_file_location("plugin_mod", ${JSON.stringify(initPath)})`,
        'mod = importlib.util.module_from_spec(spec)',
        'spec.loader.exec_module(mod)',
        '',
        'calls = {"skills": [], "hooks": {}}',
        '',
        'class FakeCtx:',
        '    def register_skill(self, name, path):',
        '        calls["skills"].append((name, path))',
        '',
        '    def register_hook(self, name, fn):',
        '        calls["hooks"][name] = fn',
        '',
        'ctx = FakeCtx()',
        'mod.register(ctx)',
        '',
        'assert calls["skills"], "expected at least one registered skill"',
        'for name, path in calls["skills"]:',
        '    assert isinstance(path, pathlib.Path), f"{name} was registered with {type(path)}, not Path"',
        '',
        'hook = calls["hooks"]["pre_llm_call"]',
        'result = hook(is_first_turn=True)',
        'assert isinstance(result, dict), f"expected a dict, got {result!r}"',
        'assert \'<plugin-bootstrap plugin="demo">\' in result["context"]',
        'assert "Demo skill body." in result["context"]',
        '',
        'print("SMOKE_TEST_OK")',
        '',
      ].join('\n'),
    )

    const stdout = execFileSync('python3', [driverPath], { encoding: 'utf8' })
    expect(stdout).toContain('SMOKE_TEST_OK')
  })

  it('tolerates a missing bootstrap file: skills still register, no pre_llm_call hook, warns to stderr', () => {
    const dir = mkdtempSync(join(tmpdir(), 'eh-hermes-exec-nobootstrap-'))
    writeFileSync(
      join(dir, 'everyharness.yaml'),
      'name: demo\nversion: 1.0.0\ndescription: missing-bootstrap fixture\nbootstrap:\n  generate: true\n',
    )
    mkdirSync(join(dir, 'skills', 'a-skill'), { recursive: true })
    writeFileSync(
      join(dir, 'skills', 'a-skill', 'SKILL.md'),
      '---\nname: a-skill\ndescription: missing-bootstrap fixture skill\n---\n\n# A Skill\n\nSkill body.\n',
    )

    const demoModel = buildModel(dir)
    const result = hermes.emit(demoModel)
    writeFileSet(dir, result.files)

    // Delete the generated bootstrap file after writing the fileset, simulating
    // a broken/incomplete install where __init__.py exists but the bootstrap
    // content it reads at runtime does not.
    rmSync(join(dir, 'hooks', 'everyharness', 'bootstrap.md'))

    const initPath = join(dir, '.hermes-plugin', '__init__.py')
    const driverPath = join(dir, 'driver.py')
    writeFileSync(
      driverPath,
      [
        'import importlib.util',
        'import pathlib',
        'import sys',
        '',
        `spec = importlib.util.spec_from_file_location("plugin_mod", ${JSON.stringify(initPath)})`,
        'mod = importlib.util.module_from_spec(spec)',
        'spec.loader.exec_module(mod)',
        '',
        'calls = {"skills": [], "hooks": {}}',
        '',
        'class FakeCtx:',
        '    def register_skill(self, name, path):',
        '        calls["skills"].append((name, path))',
        '',
        '    def register_hook(self, name, fn):',
        '        calls["hooks"][name] = fn',
        '',
        'ctx = FakeCtx()',
        'mod.register(ctx)  # must not raise despite the missing bootstrap file',
        '',
        'assert calls["skills"], "expected at least one registered skill"',
        'for name, path in calls["skills"]:',
        '    assert isinstance(path, pathlib.Path), f"{name} was registered with {type(path)}, not Path"',
        '',
        'assert "pre_llm_call" not in calls["hooks"], "no hook should be registered when bootstrap is unavailable"',
        '',
        'print("SMOKE_TEST_OK")',
        '',
      ].join('\n'),
    )

    const proc = spawnSync('python3', [driverPath], { encoding: 'utf8' })
    expect(proc.status).toBe(0)
    expect(proc.stdout).toContain('SMOKE_TEST_OK')
    expect(proc.stderr).toContain('demo plugin: bootstrap unavailable')
    expect(proc.stderr).toContain('skills registered without session bootstrap')
  })

  it('emits syntactically valid Python with multi-segment component paths (regression: path charset)', () => {
    const dir = mkdtempSync(join(tmpdir(), 'eh-hermes-multipath-'))
    writeFileSync(
      join(dir, 'everyharness.yaml'),
      'name: multi-path\nversion: 1.0.0\ndescription: multi-segment component path fixture\nbootstrap:\n  skill: example\ncomponents:\n  skills: my/skills\n',
    )
    mkdirSync(join(dir, 'my', 'skills', 'example'), { recursive: true })
    writeFileSync(
      join(dir, 'my', 'skills', 'example', 'SKILL.md'),
      '---\nname: example\ndescription: skill in nested component path\n---\n\n# Example\n\nExample skill body.\n',
    )

    const mpModel = buildModel(dir)
    const result = hermes.emit(mpModel)
    const initPy = result.files.find((f) => f.path === '.hermes-plugin/__init__.py')!.content

    // Ensure no placeholders leaked through
    expect(initPy).not.toMatch(/__[A-Z_]+__/)

    // Ensure the emitted Python is syntactically valid (this catches quote/backslash injection attacks)
    expect(pyCompile(initPy).status).toBe(0)
  })
})
