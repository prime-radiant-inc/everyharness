  '        (os.path.realpath(os.path.join(here, "..", *"__SKILLS_DIR__".split("/"))), os.path.realpath(os.path.join(here, ".."))),',
  '        (os.path.realpath(os.path.join(here, *"__SKILLS_DIR__".split("/"))), here),',
